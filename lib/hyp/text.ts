/**
 * تهيئة النصوص المرسَلة إلى صفحة دفع HYP.
 *
 * صفحة HYP تُخدَم بترميز **windows-1255** (صفحة الترميز العبرية) مهما كانت
 * قيمة PageLang — تحقّقنا من HEB وENG وARB وRUS، كلها windows-1255. وهذا
 * الترميز **لا يحوي الحرف العربي أصلًا**، فأي نص عربي يصل كعلامات استفهام:
 * «هبة حسن» تظهر «??? ???» في اللحظة التي تُدخل فيها العميلة بطاقتها.
 *
 * الحل: نقحرة عربي ← عبري. الأبجديتان ساميّتان متقاربتان فالتحويل يكاد
 * يكون حرفًا بحرف، ولا يحتاج اختراع حركات قصيرة كما تحتاج اللاتينية
 * («هبة» باللاتينية تصير «Hba» لأن العربية لا تكتب الحركات).
 * وهذه صيغة مألوفة للعربيات في إسرائيل — هكذا تُكتب أسماؤهنّ في الهوية
 * والبنك، بل هكذا يعرض ترمينال هبة اسمها أصلًا: «חסן».
 */

/** عربي ← عبري — حرفًا بحرف */
const ARABIC_TO_HEBREW: Record<string, string> = {
  "ا": "א", "أ": "א", "إ": "א", "آ": "א", "ٱ": "א", "ى": "א", "ء": "א",
  "ب": "ב", "ت": "ת", "ث": "ת", "ج": "ג", "ح": "ח", "خ": "כ",
  "د": "ד", "ذ": "ד", "ر": "ר", "ز": "ז", "س": "ס", "ش": "ש",
  "ص": "צ", "ض": "צ", "ط": "ט", "ظ": "ט", "ع": "ע", "غ": "ג",
  "ف": "פ", "ق": "ק", "ك": "כ", "ل": "ל", "م": "מ", "ن": "נ",
  "ه": "ה", "ة": "ה", "و": "ו", "ي": "י", "ئ": "י", "ؤ": "ו",
  // لام ألف والمسافة غير الفاصلة
  "لا": "לא", " ": " ",
};

/** الأرقام العربية-الهندية ← اللاتينية */
const ARABIC_DIGITS: Record<string, string> = {
  "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
  "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
};

/** الحروف العبرية ذات الصيغة النهائية (sofit) في آخر الكلمة */
const FINAL_FORMS: Record<string, string> = {
  "כ": "ך", "מ": "ם", "נ": "ן", "פ": "ף", "צ": "ץ",
};

/** نطاق التشكيل العربي — يُحذف قبل النقحرة */
const ARABIC_DIACRITICS = /[ً-ْٰـ]/g;

/** هل الحرف قابل للتمثيل في windows-1255؟ (ASCII + العبرية + علامات شائعة) */
function isEncodable(ch: string): boolean {
  const c = ch.codePointAt(0)!;
  if (c >= 0x20 && c <= 0x7e) return true;          // ASCII مطبوع
  if (c >= 0x05d0 && c <= 0x05ea) return true;      // الحروف العبرية
  if (c === 0x20aa) return true;                     // ₪
  return false;
}

/** يحوّل صيغ الحروف العبرية إلى النهائية في أواخر الكلمات */
function applyFinalForms(text: string): string {
  return text.replace(/[א-ת](?![א-ת])/g, (ch) => FINAL_FORMS[ch] ?? ch);
}

/**
 * يهيّئ نصًا لصفحة HYP: يحذف التشكيل، ينقحر العربي إلى العبري، يوحّد
 * الأرقام، ثم يسقط أي حرف يبقى غير قابل للتمثيل — فلا يصل «؟» أبدًا.
 * النص اللاتيني والعبري يمرّان كما هما.
 */
export function toHypText(value: string | undefined | null): string {
  if (!value) return "";

  let out = value.normalize("NFC").replace(ARABIC_DIACRITICS, "");

  out = [...out]
    .map((ch) => ARABIC_TO_HEBREW[ch] ?? ARABIC_DIGITS[ch] ?? ch)
    .join("");

  out = applyFinalForms(out);

  // شبكة أمان: أي حرف غير ممثَّل (صيني، إيموجي، عربي فاتنا) يُستبدل بمسافة
  out = [...out].map((ch) => (isEncodable(ch) ? ch : " ")).join("");

  return out.replace(/\s+/g, " ").trim();
}
