/**
 * تعارض المواعيد — هبة واحدة لا تُقسَّم.
 *
 * الجلسات تُفتح متوازيةً في الساعة نفسها لخدمات عدّة (استشارة · لقاء زوم ·
 * لقاء فردي) لتترك للأم حرية الاختيار. لكنها **بدائل لا مواعيد مستقلّة**:
 * أوّل حجز في إحداها يشغل وقت هبة، فكل جلسة أخرى تتقاطع معه زمنيًا — في أي
 * خدمة — لم يعد لها وجود.
 *
 * ويكفي حجزٌ واحد لتشغل الجلسةُ الوقت: ورشة جماعية سعتها خمسة وفيها أمّ واحدة
 * تعني أن هبة عندها، فلا تُحجز استشارة في الساعة نفسها — ومع ذلك تبقى الورشة
 * نفسها مفتوحة لبقيّة الأمهات (التعارض مع **غيرها** لا مع مقاعدها).
 */

/** ما يلزم من الجلسة للحكم على تقاطعها */
export interface SessionSpan {
  id: string;
  /** YYYY-MM-DD */
  date: string;
  /** HH:MM[:SS] — تُقارَن نصًّا، فالصيغة الثابتة ترتّب صحيحًا */
  start_time: string;
  /** بلا وقت انتهاء تُعامَل كلحظة بدايتها — لا نخمّن مدّة لا نعرفها */
  end_time: string | null;
}

/** نهاية الفترة — بدايتها حين لا نهاية لها */
const endOf = (s: SessionSpan) => s.end_time ?? s.start_time;

/**
 * هل تتقاطع الفترتان؟ التماس لا يُعدّ تقاطعًا: جلسة تنتهي 12:00 وأخرى تبدأ
 * 12:00 تجتمعان في يوم واحد بلا تضارب.
 */
export function spansOverlap(a: SessionSpan, b: SessionSpan): boolean {
  if (a.date !== b.date) return false;
  return a.start_time < endOf(b) && b.start_time < endOf(a);
}

/**
 * هل وقت هذه الجلسة مأخوذ بجلسة أخرى محجوزة؟
 *
 * `busy` هي الجلسات التي فيها حجز فعليّ (ولو مقعدًا واحدًا، ولو كانت محجوبة عن
 * الزبائن: الحجز اليدوي يشغل هبة كغيره). الجلسة نفسها تُستثنى بالمعرّف.
 */
export function isTimeTaken(slot: SessionSpan, busy: SessionSpan[]): boolean {
  return busy.some((other) => other.id !== slot.id && spansOverlap(slot, other));
}
