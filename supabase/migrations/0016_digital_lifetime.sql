-- 0016_digital_lifetime.sql — الكتيب الرقمي صالح مدى الحياة
--
-- كان التوكن ينتهي بعد سنة، والمكتبة تجدّده تلقائيًا — أي أنّ الوصول دائم
-- لمن تفتح مكتبتها فقط، بينما يموت رابط الإيميل وحده بعد سنة. والوعد
-- المُعلن للعميلة هو الدوام، فالبيانات هي التي تتبع الوعد لا العكس.
--
-- null = لا تنتهي — نفس اصطلاح coupons.expires_at في 0003_store.sql.
-- العمود يبقى موجودًا كي يمكن ضبط تاريخ لصفٍّ بعينه لو لزم استثناء.
--
-- الصفوف القائمة تُحرَّر أيضًا: من اشترت قبل اليوم لا تخسر كتيبها.
-- يُطبَّق بعد 0001–0015.
-- ═══════════════════════════════════════════════════════════════

alter table public.digital_downloads
  alter column expires_at drop not null;

update public.digital_downloads
  set expires_at = null
  where expires_at is not null;
