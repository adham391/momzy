-- 0028_booking_deposit.sql — العربون في التسجيل اليدوي
-- اللقاءات الحضورية التي تُرتَّب مع هبة مباشرةً: الأم تدفع عربونًا
-- عند الحجز وتُكمل المبلغ يوم اللقاء.
--   null            = لا عربون (مدفوع كاملًا، أو لم يُدفع شيء)
--   0 < قيمة < amount = عربون، والمتبقّي = amount − deposit_amount
--   = amount        = حُصّل الباقي (يبقى السجلّ ويختفي «يتبقّى»)
-- العربون يؤكّد الحجز: payment_status='paid' فيصلها رابط اللقاء
-- وتظهر في جدول اليوم — مع بقاء المتبقّي ظاهرًا لهبة كي تحصّله.
-- يُطبَّق بعد 0001–0027، **وقبل نشر الكود**.
-- ═══════════════════════════════════════════════════════════════

alter table public.bookings
  add column if not exists deposit_amount numeric(10,2);

comment on column public.bookings.deposit_amount is
  'المبلغ المقبوض فعلًا حين يكون أقلّ من amount (عربون) — null = لا عربون';
