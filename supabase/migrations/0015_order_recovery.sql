-- ═══════════════════════════════════════════════════════════════
-- 0015_order_recovery.sql — إيميل استرداد الطلبات غير المدفوعة
--
-- الطلب يُنشأ ثم تُفتح صفحة الدفع. من تعثّر دفعها أو أغلقت الصفحة يبقى
-- طلبها معلّقًا بلا أثر عندها. نرسل لها تذكيرًا **بعد مهلة** وفقط إن بقي
-- غير مدفوع — فمن دفعت لا يصلها إلا التأكيد.
--
-- العمود يمنع التكرار: يُختم فور الإرسال، فلا تصلها الرسالة مرتين مهما
-- تكرّر المسح أو تزامن.
-- يُطبَّق بعد 0001–0014.
-- ═══════════════════════════════════════════════════════════════

alter table public.orders
  add column if not exists recovery_email_sent_at timestamptz;

-- فهرس جزئي: المسح يبحث عن المعلّقة التي لم تُذكَّر بعد — وهي قلّة دائمًا
create index if not exists idx_orders_recovery_pending
  on public.orders (created_at)
  where payment_status = 'pending' and recovery_email_sent_at is null;
