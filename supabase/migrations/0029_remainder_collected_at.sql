-- 0029_remainder_collected_at.sql — لحظة تحصيل باقي المبلغ
-- مع 0028 (العربون): الإيراد يتبع **لحظة القبض** لا لحظة الحجز —
-- العربون يوم الحجز، والباقي يوم تضغط هبة «حصّلت الباقي».
--   null = لم يُحصَّل الباقي بعد (أو لا عربون أصلًا)
-- يُطبَّق بعد 0001–0028، **وقبل نشر الكود**.
-- ═══════════════════════════════════════════════════════════════

alter table public.bookings
  add column if not exists remainder_collected_at timestamptz;

comment on column public.bookings.remainder_collected_at is
  'لحظة تحصيل باقي المبلغ بعد العربون — منها يُحتسب الباقي في إيراد يومه';
