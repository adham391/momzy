alter table public.waitlist
  add column if not exists baby_name text,
  add column if not exists city text;

comment on column public.waitlist.baby_name is
  'اسم الطفل الكامل — يُطلب للمولود فقط في الخدمات ذات الفئة العمرية';

comment on column public.waitlist.city is
  'بلدة الأم كما كتبتها عند الانضمام — لتعرف هبة من أين تأتي المنتظِرات';
